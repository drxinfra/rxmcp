package rx

import "testing"

// Примеры повторяют то, что редактор веб-клиента RX 25.2 сохраняет после открытия
// карточки (сняты с истории карточек, тексты заменены).
func TestEditorMarkdown(t *testing.T) {
	cases := []struct{ name, in, want string }{
		{"пусто", "  \n", ""},
		{"абзац", "Просто текст.", "Просто текст.\n\n"},
		{"строки становятся абзацами", "Первая строка\nвторая строка", "Первая строка\n\nвторая строка\n\n"},
		{"маркеры и хвост после списка",
			"- Откуда: разбор.\n- Сделать: индекс.\n- Проверка: замер.",
			"* Откуда: разбор.\n* Сделать: индекс.\n* Проверка: замер.\n\n\\\n\n\n"},
		{"вложенный нумерованный",
			"- Сделать:\n  1. код\n  2. сборка\n- Исполнитель: мы.",
			"* Сделать:\n\n  \n  1. код\n  2. сборка\n* Исполнитель: мы.\n\n\\\n\n\n"},
		{"вложенный маркированный",
			"- Имена:\n  - первое\n  - второе\n- Дальше",
			"* Имена:\n  * первое\n  * второе\n* Дальше\n\n\\\n\n\n"},
		{"нумерованный после абзаца и в начале",
			"Что сделать:\n1. раз\n2. два",
			"Что сделать:\n\n\n1. раз\n2. два\n\n\\\n\n\n"},
		{"нумерованный первым", "1. раз\n2. два", "\n1. раз\n2. два\n\n\\\n\n\n"},
		{"номера выравниваются",
			"8. a\n9. b\n10. c",
			"\n 8. a\n 9. b\n10. c\n\n\\\n\n\n"},
		{"абзац после списка отдельно",
			"- пункт\nИсполнитель: мы",
			"* пункт\n\nИсполнитель: мы\n\n"},
		{"«* 1.» пункт с вложенным списком",
			"- 2. Таблица",
			"* \\\n  \n  2. Таблица\n\n\\\n\n\n"},
		{"экранирование",
			"Индексы logs-* и [ ] около ~30 с, путь C:\\Data, a_b_c",
			"Индексы logs-\\* и \\[ \\] около \\~30 с, путь C:\\\\Data, a_b_c\n\n"},
		{"разметка остаётся",
			"**Жирный**, *курсив*, ~~старое~~, `код *x*` и [ссылка](https://example.com/a_b)",
			"**Жирный**, *курсив*, ~~старое~~, `код *x*` и [ссылка](https://example.com/a_b)\n\n"},
		{"начало абзаца", "15.10.2026 решили\n- не список\n> не цитата", "15\\.10.2026 решили\n\n* не список\n\n\\> не цитата\n\n"},
		{"в пункте дата не экранируется", "- 15.10.2026: решили", "* 15.10.2026: решили\n\n\\\n\n\n"},
		{"перенос строки внутри абзаца",
			"первая\\\n2. вторая",
			"первая\\\n2\\. вторая\n\n"},
		{"код как есть",
			"Команда:\n```bash\nls -la *.log \\\n  | wc\t-l \n```",
			"Команда:\n\n```bash\nls -la *.log \\\n  | wc\t-l \n```\n\n"},
		{"заголовок", "## Итог\nготово", "## Итог\n\nготово\n\n"},
	}
	for _, c := range cases {
		got := EditorMarkdown(c.in)
		if got != c.want {
			t.Errorf("%s:\n got  %q\n want %q", c.name, got, c.want)
		}
		if again := EditorMarkdown(got); again != got {
			t.Errorf("%s: повторный прогон меняет текст:\n %q\n %q", c.name, got, again)
		}
	}
}

// Текст, уже сохранённый редактором, не меняется: иначе правка через rxmcp сама
// создавала бы ту же проблему.
func TestEditorMarkdownKeepsEditorOutput(t *testing.T) {
	for _, s := range []string{
		"* Откуда: разбор.\n* Связано: AB-1.\n\n\\\n\n\n",
		"Текст.\n\n\\\nпосле переноса\n\n",
		"Шаги:\n\n\n1. раз\n2. два\n\nИтог\n\n",
		"1\\. не список, а пункт текста\n\n",
		"* Имена:\n  * ЗТ\n* Порядок:\n\n  \n  1. проверка\n  2. раскатка\n\n\\\n\n\n",
		"Путь C:\\\\Data, индекс logs-\\*, около \\~5 мин\n\n",
	} {
		if got := EditorMarkdown(s); got != s {
			t.Errorf("текст редактора изменён:\n got  %q\n want %q", got, s)
		}
	}
}
